#!/usr/bin/env python3
"""Rebuild WebConfig's table of IANA time zones and their POSIX TZ rules.

The remote keeps time with a POSIX rule (the TZ environment variable), which
carries the daylight saving dates. WebConfig knows a city's IANA zone name, so
it needs this table to turn one into the other.

The rules are the footer line of each compiled zone file in the `tzdata`
package. Run again when a government changes its clocks:

    pip install --upgrade tzdata
    python3 tools/build_tz_rules.py
"""
import json
import re
from importlib import resources
from pathlib import Path

PAGE = Path(__file__).resolve().parent.parent / "webconfig" / "WebConfig 3.50.html"
START = "  /* TZ-RULES-START - generated by tools/build_tz_rules.py */"
END = "  /* TZ-RULES-END */"
# The remote's dock packet holds the rule in char[48].
MAX_RULE = 47


def rules():
    import tzdata

    base = resources.files("tzdata")
    table = {}
    for zone in (base / "zones").read_text().split():
        data = base.joinpath("zoneinfo", *zone.split("/")).read_bytes()
        rule = data.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode("ascii")
        if not rule:
            continue
        # The ESP32's C library reads a transition time as unsigned, so a
        # negative one (Greenland's "/-1") becomes midnight: an hour late, once
        # a year.
        rule = re.sub(r"/-\d+(:\d+)*", "/0", rule)
        if len(rule) > MAX_RULE:
            raise SystemExit(f"{zone}: rule is too long: {rule}")
        table.setdefault(rule, []).append(zone)
    return tzdata.IANA_VERSION, table


def main():
    version, table = rules()
    lines = [START, f"  /* IANA {version}. One rule, then every zone that uses it. */",
             "  var TZ_RULE_ZONES={"]
    items = sorted(table.items())
    for index, (rule, zones) in enumerate(items):
        comma = "," if index < len(items) - 1 else ""
        lines.append(f"    {json.dumps(rule)}:{json.dumps(' '.join(sorted(zones)))}{comma}")
    lines += ["  };", END]

    raw = PAGE.read_bytes()
    newline = "\r\n" if b"\r\n" in raw else "\n"
    page = raw.decode("utf-8")
    first = page.index(START)
    last = page.index(END, first) + len(END)
    page = page[:first] + newline.join(lines) + page[last:]
    PAGE.write_bytes(page.encode("utf-8"))
    print(f"IANA {version}: {sum(map(len, table.values()))} zones, {len(table)} rules")


if __name__ == "__main__":
    main()
